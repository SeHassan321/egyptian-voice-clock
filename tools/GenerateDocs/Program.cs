using System.Globalization;
using System.Text;
using VoiceClock.Core.Catalog;
using VoiceClock.Core.Time;

// Writes the generated reference documents next to the repository root's docs folder.
var root = args.Length > 0 ? args[0] : FindRepositoryRoot();
var engine = new TimeSpeechEngine(SpeechRules.Default);
var catalog = new RecordingCatalog(engine);

File.WriteAllText(Path.Combine(root, "docs", "ALL-TIMES.md"), AllTimes(engine), new UTF8Encoding(false));
File.WriteAllText(Path.Combine(root, "docs", "RECORDING-CATALOG.md"), Catalog(catalog), new UTF8Encoding(false));
Console.WriteLine("Generated docs/ALL-TIMES.md and docs/RECORDING-CATALOG.md");

static string AllTimes(TimeSpeechEngine engine)
{
    var sb = new StringBuilder();
    sb.AppendLine("# Every time the clock can say");
    sb.AppendLine();
    sb.AppendLine("> Generated by `tools/GenerateDocs` from the real engine and `Rules/speech-rules-ar-EG.json`. Do not edit by hand.");
    sb.AppendLine();
    sb.AppendLine("All 720 minutes of the 12-hour cycle. Morning and evening are spoken identically unless");
    sb.AppendLine("«صباحًا / مساءً» is turned on in settings, in which case that word is added at the end.");
    sb.AppendLine();

    for (var hour12 = 1; hour12 <= 12; hour12++)
    {
        sb.AppendLine(CultureInfo.InvariantCulture, $"## {hour12}:00 – {hour12}:59");
        sb.AppendLine();
        sb.AppendLine("| Time | Spoken | Clips |");
        sb.AppendLine("|---|---|---|");
        for (var minute = 0; minute < 60; minute++)
        {
            var plan = engine.BuildPlan(new TimeOnly(hour12 % 12, minute), TimeSpeechSettings.Default);
            var clips = string.Join(" + ", plan.Segments.Select(s => $"`{s.AssetId}`"));
            sb.AppendLine(CultureInfo.InvariantCulture, $"| {hour12}:{minute:00} | {plan.Text} | {clips} |");
        }

        sb.AppendLine();
    }

    return sb.ToString();
}

static string Catalog(RecordingCatalog catalog)
{
    var sb = new StringBuilder();
    sb.AppendLine("# Recording catalog");
    sb.AppendLine();
    sb.AppendLine("> Generated by `tools/GenerateDocs` from the real catalog. Do not edit by hand.");
    sb.AppendLine();
    sb.AppendLine("Every clip the app can ask for, in the order the guided recorder presents them.");
    sb.AppendLine("Each clip is stored as `voice/user/<id>.wav` (own recording) or comes from the bundled");
    sb.AppendLine("default voice. Say the text exactly as written, in one breath, with a natural tone.");
    sb.AppendLine();
    sb.AppendLine(CultureInfo.InvariantCulture, $"- Required clips: **{catalog.RequiredEntries(false).Count()}** (plus **2** more when «صباحًا / مساءً» is on)");
    sb.AppendLine(CultureInfo.InvariantCulture, $"- Optional: the spoken error message, and complete-sentence overrides for any of the 720 times (`phrase.HH.MM`)");
    sb.AppendLine();

    foreach (var group in catalog.Entries.GroupBy(e => e.Category))
    {
        sb.AppendLine(CultureInfo.InvariantCulture, $"## {Title(group.Key)}");
        sb.AppendLine();
        sb.AppendLine("| # | Id | Say | Required |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var entry in group)
        {
            var required = entry.Requirement switch
            {
                AssetRequirement.Required => "yes",
                AssetRequirement.RequiredWhenDayPeriodEnabled => "when صباحًا/مساءً is on",
                _ => "optional",
            };
            sb.AppendLine(CultureInfo.InvariantCulture, $"| {entry.Order + 1} | `{entry.Id}` | {entry.Text} | {required} |");
        }

        sb.AppendLine();
    }

    sb.AppendLine("## Complete-sentence overrides (optional)");
    sb.AppendLine();
    sb.AppendLine("Record one for a specific time only if the joined pieces sound unnatural there. Ids look like");
    sb.AppendLine("`phrase.01.43`; the sentence is the full time without صباحًا/مساءً, for example:");
    sb.AppendLine();
    foreach (var (h, m) in new[] { (1, 43), (12, 40), (11, 55) })
    {
        var entry = catalog.FullPhrase(h, m);
        sb.AppendLine(CultureInfo.InvariantCulture, $"- `{entry.Id}` → {entry.Text}");
    }

    return sb.ToString();
}

static string Title(AssetCategory category) => category switch
{
    AssetCategory.Hour => "Hours (الساعات)",
    AssetCategory.RoundMinute => "Round minutes (الدقايق المدوّرة)",
    AssetCategory.ExactMinute => "Exact minutes (باقي الدقايق)",
    AssetCategory.DayPeriod => "Day period (صباحًا ومساءً)",
    AssetCategory.Feedback => "Spoken error message (optional)",
    _ => category.ToString(),
};

static string FindRepositoryRoot()
{
    var directory = new DirectoryInfo(AppContext.BaseDirectory);
    while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "EgyptianVoiceClock.sln")))
    {
        directory = directory.Parent;
    }

    return directory?.FullName ?? throw new InvalidOperationException("Run from inside the repository.");
}
